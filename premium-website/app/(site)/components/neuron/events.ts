import { mulberry32 } from './utils';

/**
 * Микрособытия между главами.
 *
 * Главы длинные, и в паузах между ними сцена без событий выглядит зацикленной.
 * Раз в несколько секунд, с рандомом, происходит что-то мелкое: вспышка на
 * одиночном синапсе или короткий залп в одной группе импульсов. Это дешёвый
 * способ убить монотонность — событие занимает меньше секунды и не спорит с
 * хореографией главы.
 *
 * Третий тип из ТЗ — пролёт частицы мимо камеры — не реализован: это была бы
 * ещё одна отдельная система частиц со своими путями и буферами ради эффекта
 * длиной в полсекунды. Отмечено как сознательный компромисс.
 */

export type MicroEvents = {
    /** 0…1 — яркость вспышки одиночного синапса, гаснет сама */
    synapse: number;
    /** какой именно синапс горит: сравнивается с aSeed электрода */
    synapseId: number;
    /**
     * Продвинуть расписание. `onBurst` вызывается, когда выпало событие-залп:
     * саму механику залпа держит система импульсов.
     */
    update: (dt: number, onBurst: (duration: number) => void) => void;
};

export function createMicroEvents(seed: number): MicroEvents {
    const rand = mulberry32(seed);
    /** пауза до следующего события, секунды */
    let wait = 2 + rand() * 3;

    const self: MicroEvents = {
        synapse: 0,
        synapseId: -1,
        update(dt, onBurst) {
            // вспышка гаснет экспоненциально — резкий вход, мягкий выход
            if (self.synapse > 0) {
                self.synapse = Math.max(0, self.synapse - dt * 2.6);
            }

            wait -= dt;
            if (wait > 0) return;
            wait = 2.5 + rand() * 3.5;

            if (rand() < 0.55) {
                self.synapse = 1;
                self.synapseId = rand();
            } else {
                onBurst(0.9 + rand() * 0.6);
            }
        },
    };

    return self;
}
